export const INDIAN_TALUKAS: IndiaTaluka[] = STATE_TALUKA_SEEDS.flatMap((seed) =>
  seed.entries.map(([taluka, district], idx) => {
    const slug = taluka.toUpperCase().replace(/[^A-Z0-9]/g, '_');
    const offsetLat = ((idx % 5) - 2) * 0.14;
    const offsetLng = (Math.floor(idx / 5) - 2) * 0.14;
    const alertPool = REGIONAL_ALERTS[seed.region];
    const alertItem = alertPool[idx % alertPool.length];
    return {
      id: `IN-${seed.stateCode}-${slug}`,
      taluka,
      district,
      state: seed.state,
      stateCode: seed.stateCode,
      region: seed.region,
      mvu1962Active: true,
      vetPolyclinic: `${taluka} Taluka Veterinary Dispensary (${district})`,
      helpline: '1962',
      livestockFocus: seed.livestockFocus,
      alertLevel: alertItem.alertLevel,
      healthAlert: alertItem.en,
      healthAlertHi: alertItem.hi,
      healthAlertMr: alertItem.mr,
      lat: Number((seed.baseLat + offsetLat).toFixed(4)),
      lng: Number((seed.baseLng + offsetLng).toFixed(4)),
      synced: true,
      lastSyncedAt: DEFAULT_SYNC_ISO,
    };
  })
);

export function getStateTalukaSummaries(
  talukas: IndiaTaluka[] = INDIAN_TALUKAS
): StateTalukaSummary[] {
  const map = new Map<string, StateTalukaSummary>();
  for (const item of talukas) {
    const existing = map.get(item.stateCode);
    if (existing) {
      existing.talukaCount += 1;
      if (item.mvu1962Active) existing.mvuActiveCount += 1;
      existing.synced = existing.synced && item.synced;
    } else {
      map.set(item.stateCode, {
        state: item.state,
        stateCode: item.stateCode,
        region: item.region,
        talukaCount: 1,
        mvuActiveCount: item.mvu1962Active ? 1 : 0,
        synced: item.synced,
      });
    }
  }
  return Array.from(map.values());
}
